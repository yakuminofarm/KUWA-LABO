/**
 * 収支タブは設定で隠せる。隠している人に「収支タブ」の説明を見せると
 * 存在しない画面を探させることになるので、出し分ける。
 * "cost" = 収支タブが見えているときだけ / "noCost" = 隠しているときだけ
 */
export type GuideVisibility = "cost" | "noCost";

export type GuideBlock = (
  | { kind: "text"; text: string }
  | { kind: "list"; items: { term?: string; text: string; only?: GuideVisibility }[] }
  | { kind: "steps"; items: { title: string; text: string }[] }
  | { kind: "tip"; text: string }
) & { only?: GuideVisibility };

export interface GuideSection {
  id: string;
  /** 収支タブを隠している人には出さない章 */
  only?: GuideVisibility;
  /** lucide のアイコン名。GuideSheet 側で対応表を持つ */
  icon: string;
  title: string;
  blocks: GuideBlock[];
}

